#!/usr/bin/env python3
"""Regenerate tests/unit/message_golden_test.c3 from python-dbus-next.

The little-endian messages are produced by dbus-next's own marshaller
(dbus_next.message.Message._marshall), an independent implementation of the
D-Bus wire format. The big-endian message is the same little-endian Hello with
its four integer header words byte-swapped (the only integers it has). The
wrongly typed PATH is assembled with dbus-next's Marshaller from a PATH field
holding a STRING, which dbus-next itself would not produce.

Usage:  python3 -I gen_message_vectors.py <venv-with-dbus-next>/bin/python  > ../unit/message_golden_test.c3
(run it with a Python that has dbus-next; the output is written to stdout)
"""
import struct
import sys

from dbus_next import Message, MessageType, Variant
from dbus_next._private.marshaller import Marshaller


def hexdump(data: bytes) -> str:
    return " ".join(f"{b:02x}" for b in data)


def message(**kwargs) -> bytes:
    return Message(**kwargs)._marshall()


hello = message(destination='org.freedesktop.DBus', path='/org/freedesktop/DBus',
                interface='org.freedesktop.DBus', member='Hello', serial=1)
get_name_owner = message(destination='org.freedesktop.DBus', path='/org/freedesktop/DBus',
                         interface='org.freedesktop.DBus', member='GetNameOwner', signature='s',
                         body=['org.freedesktop.DBus'], serial=2)
signal = message(message_type=MessageType.SIGNAL, path='/org/x/Obj', interface='org.x.Iface',
                 member='Changed', signature='sa{sv}', body=['Name', {'Count': Variant('u', 7)}], serial=3)
error = message(message_type=MessageType.ERROR, error_name='org.freedesktop.DBus.Error.UnknownMethod',
                reply_serial=2, destination=':1.5', signature='s', body=['no such method'], serial=4)
method_return = message(message_type=MessageType.METHOD_RETURN, reply_serial=2, destination=':1.5',
                        signature='s', body=[':1.9'], serial=5)

class BigEndianBuffer:
    """Just enough of the wire format to write a big-endian Hello by hand.

    Every integer is big-endian; each value is aligned to its natural boundary
    counted from the start of the buffer, with NUL padding (spec "Byte order and
    alignment").
    """

    def __init__(self):
        self.data = bytearray()

    def align(self, n):
        self.data += b"\0" * ((n - len(self.data) % n) % n)

    def byte(self, v):
        self.data.append(v)

    def u32(self, v):
        self.align(4)
        self.data += struct.pack(">I", v)

    def text(self, s):
        self.u32(len(s.encode()))
        self.data += s.encode() + b"\0"

    def signature(self, s):
        self.byte(len(s))
        self.data += s.encode() + b"\0"


def big_endian_hello(path, interface, member, destination, serial):
    fields = BigEndianBuffer()
    for code, sig, value in ((1, 'o', path), (2, 's', interface), (3, 's', member), (6, 's', destination)):
        fields.align(8)
        fields.byte(code)
        fields.signature(sig)
        fields.text(value)
    buf = BigEndianBuffer()
    buf.byte(ord('B'))
    buf.byte(1)
    buf.byte(0)
    buf.byte(1)
    buf.u32(0)            # body length
    buf.u32(serial)
    buf.u32(len(fields.data))  # length of the field array, excluding its padding
    buf.align(8)          # the field array starts on an 8-byte boundary
    buf.data += fields.data
    buf.align(8)          # the body (empty) starts on an 8-byte boundary
    return bytes(buf.data)


hello_be = big_endian_hello('/org/freedesktop/DBus', 'org.freedesktop.DBus', 'Hello', 'org.freedesktop.DBus', 1)

# A header whose PATH field is a STRING instead of an OBJECT_PATH.
bad_fields = [[1, Variant('s', '/org/freedesktop/DBus')], [3, Variant('s', 'Hello')]]
header = Marshaller('yyyyuua(yv)', [ord('l'), 1, 0, 1, 0, 2, bad_fields])
header.marshall()
header.align(8)
bad_path_type = bytes(header.buffer)

cases = [
    ("HELLO", hello, "A METHOD_CALL Hello to the bus daemon, serial 1."),
    ("HELLO_BIG_ENDIAN", hello_be, "The same Hello, big-endian (header integers swapped)."),
    ("GET_NAME_OWNER", get_name_owner, "A METHOD_CALL with one STRING argument, serial 2."),
    ("SIGNAL", signal, "A SIGNAL with a STRING and an a{sv} argument, serial 3."),
    ("ERROR", error, "An ERROR reply to serial 2, with a string argument, serial 4."),
    ("METHOD_RETURN", method_return, "A METHOD_RETURN to serial 2, with a STRING, serial 5."),
    ("PATH_IS_A_STRING", bad_path_type, "A header whose PATH field is a STRING: invalid."),
]

out = []
out.append("// GENERATED by tests/golden/gen_message_vectors.py from python-dbus-next. Do not edit.")
out.append("module bleu::dbus::message_golden_test;")
out.append("import bleu::dbus::message, bleu::dbus::marshal, bleu::dbus::value, bleu::dbus::testing, bleu::error;")
out.append("")
for name, data, comment in cases:
    out.append(f"// {comment}")
    out.append(f'const {name} = "{hexdump(data)}";')
    out.append("")
out.append("""fn String bytes_of(String hex_text) @inline => testing::from_hex(hex_text);

// The Hello, encoded by this library, equals dbus-next's bytes.
fn void encodes_hello_like_dbus_next() @test
{
	@pool()
	{
		Message* m = message::method_call(mem, "org.freedesktop.DBus", "/org/freedesktop/DBus",
			"org.freedesktop.DBus", "Hello")!!;
		m.serial = 1;
		DString out;
		out.init(tmem);
		m.encode(&out)!!;
		testing::expect_bytes(out.str_view(), HELLO);
		m.release();
	};
}

// A GetNameOwner call with a string argument, encoded from a body writer.
fn void encodes_a_call_with_arguments_like_dbus_next() @test
{
	@pool()
	{
		Message* m = message::method_call(mem, "org.freedesktop.DBus", "/org/freedesktop/DBus",
			"org.freedesktop.DBus", "GetNameOwner")!!;
		m.serial = 2;
		Writer* w = m.body_writer("s")!!;
		w.append_string("org.freedesktop.DBus")!!;
		DString out;
		out.init(tmem);
		m.encode(&out)!!;
		testing::expect_bytes(out.str_view(), GET_NAME_OWNER);
		m.release();
	};
}

// A signal with a dictionary argument, encoded from a body writer.
fn void encodes_a_signal_like_dbus_next() @test
{
	@pool()
	{
		Message* m = message::signal(mem, "/org/x/Obj", "org.x.Iface", "Changed")!!;
		m.serial = 3;
		Writer* w = m.body_writer("sa{sv}")!!;
		w.append_string("Name")!!;
		w.begin_array("a{sv}")!!;
		w.begin_dict_entry()!!;
		w.append_string("Count")!!;
		w.begin_variant("u")!!;
		w.append_u32(7)!!;
		w.end_variant()!!;
		w.end_dict_entry()!!;
		w.end_array()!!;
		DString out;
		out.init(tmem);
		m.encode(&out)!!;
		testing::expect_bytes(out.str_view(), SIGNAL);
		m.release();
	};
}

// An ERROR reply and a METHOD_RETURN, built from a call they answer.
fn void encodes_replies_like_dbus_next() @test
{
	@pool()
	{
		Message* call = message::method_call(mem, "", "/x", "a.b", "M")!!;
		call.serial = 2;
		call.sender = ":1.5";
		Message* err = message::error_reply(mem, call, "org.freedesktop.DBus.Error.UnknownMethod", "no such method")!!;
		err.serial = 4;
		DString out;
		out.init(tmem);
		err.encode(&out)!!;
		testing::expect_bytes(out.str_view(), ERROR);
		err.release();

		Message* ret = message::reply(mem, call)!!;
		ret.serial = 5;
		Writer* w = ret.body_writer("s")!!;
		w.append_string(":1.9")!!;
		DString again;
		again.init(tmem);
		ret.encode(&again)!!;
		testing::expect_bytes(again.str_view(), METHOD_RETURN);
		ret.release();
		call.release();
	};
}

// Parsing the dbus-next bytes gives back the same header fields.
fn void parses_hello() @test
{
	@pool()
	{
		Message* m = message::parse(mem, bytes_of(HELLO))!!;
		assert(m.type == METHOD_CALL);
		assert(m.serial == 1);
		assert(m.flags == 0);
		assert(m.path == "/org/freedesktop/DBus");
		assert(m.interface_name == "org.freedesktop.DBus");
		assert(m.member == "Hello");
		assert(m.destination == "org.freedesktop.DBus");
		assert(m.signature.len == 0);
		assert(m.body.len == 0);
		m.release();
	};
}

// A big-endian message parses to the same fields as its little-endian twin.
fn void parses_big_endian_hello() @test
{
	@pool()
	{
		Message* m = message::parse(mem, bytes_of(HELLO_BIG_ENDIAN))!!;
		assert(m.big_endian);
		assert(m.serial == 1);
		assert(m.member == "Hello");
		m.release();
	};
}

// The body of a signal reads back as its signature says.
fn void parses_signal_body() @test
{
	@pool()
	{
		Message* m = message::parse(mem, bytes_of(SIGNAL))!!;
		assert(m.type == SIGNAL);
		assert(m.interface_name == "org.x.Iface");
		Reader r = m.reader()!!;
		assert(r.read_string()!! == "Name");
		Value dict = r.read_value(tmem)!!;
		assert(dict.dict_get("Count")!!.as_u32()!! == 7);
		r.finish()!!;
		m.release();
	};
}

// The error text and reply serial of an ERROR, and the reply of a METHOD_RETURN.
fn void parses_replies() @test
{
	@pool()
	{
		Message* err = message::parse(mem, bytes_of(ERROR))!!;
		assert(err.is_error());
		assert(err.reply_serial == 2);
		assert(err.error_name == "org.freedesktop.DBus.Error.UnknownMethod");
		assert(err.error_text()!! == "no such method");
		err.release();
		Message* ret = message::parse(mem, bytes_of(METHOD_RETURN))!!;
		assert(ret.type == METHOD_RETURN);
		assert(ret.destination == ":1.5");
		testing::@expect_fault(ret.error_text(), error::INVALID_STATE);
		ret.release();
	};
}

// The framing length of a message comes from its fixed header alone.
fn void frames_messages_from_their_prefix() @test
{
	assert((message::frame_length(bytes_of(HELLO)) ?? 0) == 128);
	assert((message::frame_length(bytes_of(SIGNAL)) ?? 0) == 132);
	assert((message::frame_length(bytes_of(HELLO_BIG_ENDIAN)) ?? 0) == 128);
}

// Malformed messages are refused with PROTOCOL.
fn void rejects_malformed_messages() @test
{
	@pool()
	{
		DString copy;
		copy.init(tmem);
		copy.append_bytes(bytes_of(HELLO));
		copy.set(8, 0);
		copy.set(9, 0);
		copy.set(10, 0);
		copy.set(11, 0);
		testing::@expect_fault(message::parse(tmem, copy.str_view()), error::PROTOCOL);
	};
	@pool()
	{
		DString copy;
		copy.init(tmem);
		copy.append_bytes(bytes_of(HELLO));
		copy.set(0, 'X');
		testing::@expect_fault(message::parse(tmem, copy.str_view()), error::PROTOCOL);
	};
	@pool()
	{
		DString copy;
		copy.init(tmem);
		copy.append_bytes(bytes_of(HELLO));
		copy.set(3, 2);
		testing::@expect_fault(message::parse(tmem, copy.str_view()), error::PROTOCOL);
	};
	@pool()
	{
		testing::@expect_fault(message::parse(tmem, bytes_of(PATH_IS_A_STRING)), error::PROTOCOL);
	};
	@pool()
	{
		DString copy;
		copy.init(tmem);
		copy.append_bytes(bytes_of(HELLO));
		copy.append_char(0);
		testing::@expect_fault(message::parse(tmem, copy.str_view()), error::PROTOCOL);
	};
	@pool()
	{
		// A body length of 2^27 makes the message exactly the 128 MiB limit: refused.
		DString copy;
		copy.init(tmem);
		copy.append_bytes(bytes_of(HELLO));
		copy.set(4, 0);
		copy.set(5, 0);
		copy.set(6, 0);
		copy.set(7, 0x08);
		testing::@expect_fault(message::frame_length(copy.str_view()), error::PROTOCOL);
	};
}
""")
sys.stdout.write("\n".join(out))
