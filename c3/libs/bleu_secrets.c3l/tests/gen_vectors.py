#!/usr/bin/env python3
"""Generate the known-answer vectors used by the pure crypto tests.

Writes ../src/bignum_vectors_test.c3 and ../src/session_vectors_test.c3.

  DH: pow(y, x, p) with p the RFC 2409 group 2 prime (Python int pow).
  HKDF-SHA256 (no salt, empty info, 16 bytes): hmac/hashlib, RFC 5869 construction.
  AES-128-CBC with PKCS#7: the openssl command line (openssl enc) and the
  python `cryptography` package, which must agree with each other.

Run with a fixed seed, so the vectors are reproducible:
  python3 libs/bleu_secrets.c3l/tests/gen_vectors.py
"""
import hashlib
import hmac
import os
import random
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "src"

# RFC 2409 section 6.2 (Second Oakley Group): 1024-bit MODP prime, generator 2.
P_HEX = (
    "FFFFFFFFFFFFFFFFC90FDAA22168C234C4C6628B80DC1CD129024E088A67CC74"
    "020BBEA63B139B22514A08798E3404DDEF9519B3CD3A431B302B0A6DF25F14374FE1356D6D51C245"
    "E485B576625E7EC6F44C42E9A637ED6B0BFF5CB6F406B7EDEE386BFB5A899FA5"
    "AE9F24117C4B1FE649286651ECE65381FFFFFFFFFFFFFFFF"
)
P = int(P_HEX, 16)
assert P.bit_length() == 1024


def hkdf16(ikm: bytes) -> bytes:
    """RFC 5869 with salt absent (HashLen zeros) and empty info, L = 16."""
    prk = hmac.new(b"\x00" * 32, ikm, hashlib.sha256).digest()
    return hmac.new(prk, b"\x01", hashlib.sha256).digest()[:16]


def openssl_cbc(key: bytes, iv: bytes, plain: bytes) -> bytes:
    out = subprocess.run(
        ["openssl", "enc", "-aes-128-cbc", "-K", key.hex(), "-iv", iv.hex()],
        input=plain, capture_output=True, check=True,
    ).stdout
    return out


def cryptography_cbc(key: bytes, iv: bytes, plain: bytes) -> bytes:
    from cryptography.hazmat.primitives import padding
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
    padder = padding.PKCS7(128).padder()
    padded = padder.update(plain) + padder.finalize()
    enc = Cipher(algorithms.AES(key), modes.CBC(iv)).encryptor()
    return enc.update(padded) + enc.finalize()


def c_bytes(data: bytes) -> str:
    return '"' + data.hex() + '"'


def write(name: str, text: str) -> None:
    path = SRC / name
    path.write_text(text)
    print("wrote", path)


def bignum_file(rng: random.Random) -> str:
    # (y, x) pairs: edge cases first, then random 1024-bit exponents.
    pairs = [(2, 0), (2, 1), (P - 2, 2), (2, P - 2), (P - 2, P - 3)]
    for i in range(8):
        x = rng.getrandbits(1024) | (1 << 1023) if i < 4 else rng.getrandbits(1024)
        pairs.append((rng.randrange(2, P - 1), x))
    rows = []
    for y, x in pairs:
        rows.append((y.to_bytes(128, "big"), x.to_bytes(128, "big"), pow(y, x, P).to_bytes(128, "big")))
    body = "\n".join("\t{ " + ", ".join('"' + part.hex() + '"' for part in row) + " }," for row in rows)
    return f"""<*
 GENERATED by libs/bleu_secrets.c3l/tests/gen_vectors.py. Do not edit by hand.

 Known answers for modular exponentiation modulo the RFC 2409 group 2 prime.
 Each row is (y, x, y^x mod p): hex strings of 128 big-endian bytes, computed
 with Python's int pow.
*>
module bleu::secrets::bignum_vectors_test;

const String[3][{len(rows)}] DH_VECTORS = {{
{body}
}};
"""


def session_file(rng: random.Random) -> str:
    hkdf_rows = []
    for n in (128, 1, 32, 33):
        ikm = rng.getrandbits(8 * n).to_bytes(n, "big")
        hkdf_rows.append((ikm, hkdf16(ikm)))
    cbc_rows = []
    for n in (0, 1, 15, 16, 17, 31, 32, 100):
        key = rng.getrandbits(128).to_bytes(16, "big")
        iv = rng.getrandbits(128).to_bytes(16, "big")
        plain = rng.getrandbits(8 * n).to_bytes(n, "big") if n else b""
        ossl = openssl_cbc(key, iv, plain)
        crypto = cryptography_cbc(key, iv, plain)
        if ossl != crypto:
            sys.exit(f"openssl and cryptography disagree for length {n}")
        cbc_rows.append((key, iv, plain, ossl))
    hk = "\n".join("\t{ " + c_bytes(ikm) + ", " + c_bytes(out) + " }," for ikm, out in hkdf_rows)
    cb = "\n".join(
        "\t{ " + ", ".join(c_bytes(part) for part in (k, iv, pl, ct)) + " },"
        for k, iv, pl, ct in cbc_rows
    )
    return f"""<*
 GENERATED by libs/bleu_secrets.c3l/tests/gen_vectors.py. Do not edit by hand.

 HKDF-SHA256 (salt absent, empty info, 16-byte output): rows are (ikm, okm),
 computed with Python hmac/hashlib. AES-128-CBC with PKCS#7 padding: rows are
 (key, iv, plaintext, ciphertext), where the ciphertext was produced by
 `openssl enc -aes-128-cbc` and matched by the python `cryptography` package.
*>
module bleu::secrets::session_vectors_test;

const String[2][{len(hkdf_rows)}] HKDF_VECTORS = {{
{hk}
}};

const String[4][{len(cbc_rows)}] CBC_VECTORS = {{
{cb}
}};
"""


def main() -> None:
    rng = random.Random(0x5EC4E7)
    write("bignum_vectors_test.c3", bignum_file(rng))
    write("session_vectors_test.c3", session_file(rng))


if __name__ == "__main__":
    main()
