#!/usr/bin/env python3
"""Turn the header c3c writes for libbleu_capi into the public C headers.

    genheader.py --header <c3c-output>/libbleu_capi.h --src libs/bleu_capi.c3l/src \
                 --libs libs --out include/bleu [--exports FILE] [--check]

c3c's header describes every type the exported functions reach, under C3's
mangled names, with C3 idioms (global-variable enum members, `c3slice_t`,
`c3fault_t`). This tool writes the public C API from it:

* Names keep their C3 export names (`bleu_battery_open`). Types from other Bleu
  modules, which C3 mangles (`bleu_battery__State`, `bleu_capi_battery_api__BatteryListener`),
  become `bleu_battery_state_t`, `bleu_battery_listener_t`.
* Enum members become `#define BLEU_BATTERY_BACKEND_AUTO 0` (C3 emits them as
  global variables, which every translation unit would define).
* `String` and `c3slice_t` become `bleu_slice_t`; `ZString` becomes `char`;
  `uint8_t` pointers and arrays are `char` (C3's `char`).
* `char*` is `const char*` when returned or stored in a field; a struct pointer
  returned from an accessor is `const`, and so is an input struct parameter. Out
  parameters (named `out*`) and opaque handles are not const.
* Only types reachable from an exported function are emitted. A fault, `any`,
  `typeid` or C3 identifier in an emitted declaration is an error.
* `<* ... *>` blocks that precede an `@export` declaration (or an alias) become C
  comments. A struct marked `// capi:opaque` is declared but not defined.
* `bleu/core.h` holds the shared types; `bleu/<service>.h` one header per service
  in SERVICES; `bleu/bleu.h` includes them all.
* With --exports, also writes the exact list of exported function names, which
  build.sh turns into the linker version script.

Output is deterministic. --check writes nothing and fails when the files differ.
"""

import argparse
import os
import re
import sys

# Services with a C API. A new service is added here together with its `*_api.c3`.
SERVICES = ["battery", "brightness"]

# Text that must never reach a public header.
FORBIDDEN = re.compile(r"c3fault_t|c3any_t|c3typeid_t|c3slice_t|\$|\bstd_|\bString\b|\bZString\b|__")

IDENT = re.compile(r"[A-Za-z_]\w*(?:\$[\w.]*\$)?")
C_BUILTINS = {"void", "char", "bool", "int", "int32_t", "uint32_t", "int64_t", "uint64_t", "uint8_t",
              "size_t", "float", "double", "const", "unsigned", "long", "short", "ptrdiff_t"}

PREAMBLE = """\
/* Generated by tools/capi/genheader.py from libs/bleu_capi.c3l/src. Do not edit.
 * Regenerate with tools/capi/build.sh. C ABI version {abi}.
 */
"""

SLICE_DEFINITION = """\
/* A run of `len` elements starting at `ptr`. The element type is named in the
 * comment of each field that holds one. The slice borrows: never free it. */
typedef struct bleu_slice_t
{
	void* ptr;
	size_t len;
} bleu_slice_t;
"""


class Fail(Exception):
    pass


def snake(name):
    """CamelCase to snake_case: `BatteryListener` -> `battery_listener`."""
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", s)
    return s.lower()


def clean_type(c3name):
    """The public C name for a C3 type name; unchanged when it is already a C name."""
    m = re.fullmatch(r"bleu_capi(?:_\w+)?__(\w+)", c3name)
    if m:
        return "bleu_%s_t" % snake(m.group(1))
    m = re.fullmatch(r"bleu_(\w+?)__(\w+)", c3name)
    if m:
        if snake(m.group(2)) == m.group(1):  # bleu::availability::Availability -> bleu_availability_t
            return "bleu_%s_t" % m.group(1)
        return "bleu_%s_%s_t" % (m.group(1), snake(m.group(2)))
    m = re.fullmatch(r"std_collections_maybe__Maybe\$(.+)\$", c3name)
    if m:
        return "bleu_maybe_%s_t" % snake(m.group(1).split(".")[-1])
    return c3name


def upper_of(c_name):
    """`bleu_battery_backend_t` -> `BLEU_BATTERY_BACKEND`."""
    base = c_name[:-2] if c_name.endswith("_t") else c_name
    return base.upper()


def service_of(c_name):
    for svc in SERVICES:
        if c_name.startswith("bleu_%s_" % svc):
            return svc
    return "core"


# ------------------------------------------------------------ c3c header

def statements(lines):
    """Top-level C statements: each ends at a `;` that is outside braces."""
    out, buf, depth = [], [], 0
    for line in lines:
        if not buf and not line.strip():
            continue
        buf.append(line)
        depth += line.count("{") - line.count("}")
        if depth == 0 and line.rstrip().endswith(";"):
            out.append("\n".join(buf).strip())
            buf = []
    if "".join(buf).strip():
        raise Fail("unterminated declaration: %r" % buf[0])
    return out


def classify(stmt):
    """One c3c declaration as a dict with `kind` and its C3 name."""
    m = re.match(r"typedef enum ([^\s{]+)\s*\{(.*)\}\s*([^\s;]+);$", stmt, re.S)
    if m:
        members = [x.strip().rstrip(",") for x in m.group(2).split("\n") if x.strip()]
        return {"kind": "enum_body", "c3": m.group(3), "members": members}
    m = re.match(r"typedef struct ([^\s;]+)(?:\s+([^\s;]+))?\s*;$", stmt)
    if m:
        return {"kind": "forward", "c3": m.group(2) or m.group(1)}
    m = re.match(r"struct ([^\s{]+)\s*\{(.*)\};$", stmt, re.S)
    if m:
        fields = [x.strip() for x in m.group(2).split(";") if x.strip()]
        tag = m.group(1)
        if tag.endswith("__"):  # c3c names the body after its typedef, with a `__` suffix
            tag = tag[:-2]
        return {"kind": "struct", "c3": tag, "fields": fields}
    m = re.match(r"typedef (.+?)\(\*([^\s)]+)\)\((.*)\);$", stmt, re.S)
    if m:
        return {"kind": "fnptr", "c3": m.group(2), "ret": m.group(1).strip(), "params": m.group(3)}
    m = re.match(r"typedef (uint8_t|uint16_t|uint32_t|int32_t|int64_t|uint64_t|float|double|bool|int8_t) (\w+);$", stmt)
    if m:
        return {"kind": "scalar_typedef", "c3": m.group(2), "target": m.group(1)}
    m = re.match(r"typedef (.+) ([^\s;]+);$", stmt, re.S)
    if m:
        return {"kind": "typedef", "c3": m.group(2), "target": m.group(1).strip()}
    m = re.match(r"([^\s]+) ([^\s]+) = (-?\d+);$", stmt)
    if m:
        return {"kind": "constant", "c3": m.group(2), "type": m.group(1), "value": int(m.group(3))}
    # Unions and other shapes: only reachable ones matter, and reachability reports those.
    return {"kind": "other", "c3": "", "stmt": stmt}


def parse_c3_header(text):
    """(items, functions) from c3c's header; items in c3c's (dependency) order."""
    if "/* TYPES */" not in text or "/* FUNCTIONS */" not in text:
        raise Fail("not a c3c library header: no /* TYPES */ or /* FUNCTIONS */ section")
    types_text = text.split("/* TYPES */", 1)[1].split("/* FUNCTIONS */", 1)[0]
    funcs_text = text.split("/* FUNCTIONS */", 1)[1]
    items = [classify(s) for s in statements(types_text.split("\n"))]
    funcs = []
    for line in funcs_text.split("\n"):
        line = line.strip()
        if not line:
            continue
        if not (line.startswith("extern ") and line.endswith(";")):
            raise Fail("unexpected line in the function section: %r" % line)
        funcs.append(line[len("extern "):-1])
    return items, funcs


def resolve_enums(items):
    """Turn each enum into {kind: enum, c3, base, members: [(name, value)]}."""
    constants = {}
    for it in items:
        if it["kind"] == "constant":
            constants.setdefault(it["type"], []).append(it)
    out = []
    for it in items:
        k = it["kind"]
        if k == "enum_body":
            prefix = it["c3"] + "_"
            members = []
            for i, raw in enumerate(it["members"]):
                if not raw.startswith(prefix):
                    raise Fail("enum member %s does not start with %s" % (raw, prefix))
                members.append((raw[len(prefix):], i))
            out.append({"kind": "enum", "c3": it["c3"], "base": "int32_t", "members": members})
        elif k == "scalar_typedef" and it["target"] == "uint8_t" and it["c3"] in constants:
            prefix = it["c3"] + "_"
            members = []
            for c in constants[it["c3"]]:
                if not c["c3"].startswith(prefix):
                    raise Fail("enum constant %s does not start with %s" % (c["c3"], prefix))
                members.append((c["c3"][len(prefix):], c["value"]))
            out.append({"kind": "enum", "c3": it["c3"], "base": "uint8_t", "members": members})
        elif k == "constant":
            continue
        else:
            out.append(it)
    return out


# ----------------------------------------------------------- docs

DECL_HEAD = re.compile(r"(fn|struct|enum|typedef|alias|constset|bitstruct)\s+(\w+)")


def collect_docs(path):
    """The declarations of one C3 file, each with the doc block before it.

    Returns a list of (names, doc, opaque). `names` are the keys a declaration is
    known by: its @export name, or for aliases and types the C3 name, as
    `alias:<Name>` / `type:<Name>`. `opaque` is true after a `// capi:opaque` line.
    """
    lines = open(path, encoding="utf-8").read().split("\n")
    found = []
    block = None   # lines of a doc block that is still open
    doc = ""       # the last closed doc block, until the next declaration takes it
    marked = False
    for i, raw in enumerate(lines):
        s = raw.strip()
        if block is not None:
            closes = s.endswith("*>")
            body = s[:-2].strip() if closes else s
            if body:
                block.append(body)
            if closes:
                doc = "\n".join(block)
                block = None
            continue
        if s.startswith("<*"):
            rest = s[2:].strip()
            if rest.endswith("*>"):
                doc = rest[:-2].strip()
            else:
                block = [rest] if rest else []
            continue
        if s == "// capi:opaque":
            marked = True
            continue
        if not s or s.startswith("//"):
            continue
        head = DECL_HEAD.match(s)
        if not head:
            doc, marked = "", False
            continue
        header = " ".join(x.strip() for x in lines[i:i + 8]).split("{")[0].split(";")[0]
        export = re.search(r'@export\("([^"]+)"\)', header)
        if export:
            names = [export.group(1)]
        elif head.group(1) == "alias":
            names = ["alias:" + head.group(2)]
        elif head.group(1) != "fn":
            names = ["type:" + head.group(2)]
        else:
            names = []
        if names:
            found.append((names, doc, marked))
        doc, marked = "", False
    return found


def doc_tables(src_files, libs_dir):
    """`own`: doc and opaque status of this library's declarations, by export or alias key.
    `others`: doc of other libraries' types, by (library, C3 name), for the mangled names."""
    own, opaque, others = {}, set(), {}
    for path in src_files:
        for names, doc, is_opaque in collect_docs(path):
            for name in names:
                if doc:
                    own.setdefault(name, doc)
                if is_opaque and not name.startswith(("alias:", "type:")):
                    opaque.add(name)
    for lib in sorted(os.listdir(libs_dir)):
        src = os.path.join(libs_dir, lib, "src")
        if not lib.endswith(".c3l") or not os.path.isdir(src):
            continue
        for fn in sorted(os.listdir(src)):
            if not fn.endswith(".c3") or fn.endswith("_test.c3"):
                continue
            for names, doc, _ in collect_docs(os.path.join(src, fn)):
                for name in names:
                    if name.startswith("type:") and doc:
                        others.setdefault((lib[:-4], name[len("type:"):]), doc)
    return own, opaque, others


# ----------------------------------------------------------- rewriting

class Namer:
    """Maps C3 spellings to public C spellings."""

    def __init__(self, items):
        self.subst = {"String": "c3slice_t", "ZString": "uint8_t*"}
        for it in items:
            if it["kind"] in ("typedef", "scalar_typedef", "fnptr") and not it["c3"].startswith("bleu_"):
                self.subst[it["c3"]] = it.get("target", it.get("ret"))
        self.known = {it["c3"] for it in items if it["kind"] in ("struct", "enum", "typedef", "fnptr", "scalar_typedef")}

    def text(self, text):
        text = text.replace("c3slice_t", "bleu_slice_t")
        text = IDENT.sub(lambda m: self._ident(m.group(0)), text)
        text = re.sub(r"\buint8_t(\s*\*|\s+\w+\s*\[)", r"char\1", text)
        return text

    def _ident(self, name):
        if name == "String" or name == "c3slice_t":
            return "bleu_slice_t"
        if name in self.subst:
            return self.text(self.subst[name])
        if name.startswith(("bleu_", "std_")):
            return clean_type(name)
        return name


def const_return(ret, structs, opaque):
    m = re.fullmatch(r"(\w+)\s*\*", ret)
    if m and m.group(1) in structs and m.group(1) not in opaque:
        return "const %s*" % m.group(1)
    if ret == "char*":
        return "const char*"
    return ret


def const_params(params, structs, opaque):
    out = []
    for p in [x.strip() for x in params.split(",")]:
        m = re.fullmatch(r"(\w+)\s*\*\s*(\w+)", p)
        if m and m.group(1) in structs and m.group(1) not in opaque and not m.group(2).startswith("out"):
            p = "const %s* %s" % (m.group(1), m.group(2))
        out.append(p)
    return ", ".join(out)


def generate(header, src_dir, libs_dir):
    items, funcs = parse_c3_header(open(header, encoding="utf-8").read())
    items = resolve_enums(items)
    namer = Namer(items)
    src_files = [os.path.join(src_dir, f) for f in sorted(os.listdir(src_dir))
                 if f.endswith(".c3") and not f.endswith("_test.c3")]
    own, opaque_names, others = doc_tables(src_files, libs_dir)
    core_src = open(os.path.join(src_dir, "core.c3"), encoding="utf-8").read()
    abi = re.search(r"const uint ABI_VERSION = (\d+);", core_src)
    if not abi:
        raise Fail("core.c3 has no `const uint ABI_VERSION = N;`")

    decls, order = {}, []
    # Exported names first, so that a mangled internal type with the same C name never wins.
    ordered = sorted(enumerate(items), key=lambda p: 0 if p[1].get("c3") == clean_type(p[1].get("c3", "")) else 1)
    for index, it in ordered:
        k = it["kind"]
        if k in ("forward", "constant", "other"):
            continue
        c3 = it["c3"]
        if k == "typedef" and c3 in namer.subst:
            continue
        if k == "typedef" and c3.startswith("std_"):
            continue
        clean = clean_type(c3)
        doc = own.get(c3, "")
        if not doc and c3.startswith("bleu_capi"):
            doc = own.get("alias:" + c3.split("__")[-1], "")
        if not doc and c3.startswith("bleu_") and "__" in c3 and not c3.startswith("bleu_capi"):
            mod, name = c3[len("bleu_"):].split("__", 1)
            for lib in ("bleu_" + mod, "bleu_core"):
                doc = doc or others.get((lib, name), "")
        if k == "typedef":
            target = namer.text(it["target"])
            body = "typedef %s %s;" % (target, clean)
            deps = set(IDENT.findall(target))
        elif k == "scalar_typedef":
            body = "typedef %s %s;" % (it["target"], clean)
            deps = set()
        elif k == "enum":
            body = "typedef %s %s;" % (it["base"], clean)
            deps = set()
        elif k == "fnptr":
            ret = namer.text(it["ret"])
            # A callback receives borrowed data: struct pointers in its parameters are const.
            params = re.sub(r"(bleu_\w+_t)\*(\s*\w+)", r"const \1*\2", namer.text(it["params"]))
            body = "typedef %s(*%s)(%s);" % (ret, clean, params)
            deps = set(IDENT.findall(ret + " " + params))
        elif k == "struct":
            if c3 in opaque_names or clean in opaque_names:
                body = None
                deps = set()
            else:
                fields = []
                deps = set()
                for f in it["fields"]:
                    ft = namer.text(f)
                    m = re.fullmatch(r"char\*(\s*\w+)", ft.replace("const ", ""))
                    if m:
                        ft = "const char*" + m.group(1)
                    fields.append(ft)
                    deps |= set(IDENT.findall(ft))
                body = "struct %s\n{\n%s\n};" % (clean, "\n".join("\t%s;" % f for f in fields))
        else:
            raise Fail("unhandled declaration kind %s for %s" % (k, c3))
        if clean in decls and clean != c3:
            continue  # a mangled internal type with the same name as an export: the export wins
        if clean in decls:
            raise Fail("two C3 types map to %s" % clean)
        decls[clean] = {"index": index, "kind": k, "body": body, "deps": deps, "doc": doc,
                        "opaque": clean in opaque_names or c3 in opaque_names,
                        "service": service_of(clean), "members": it.get("members", []),
                        "base": it.get("base")}

    order = sorted(decls, key=lambda n: decls[n]["index"])  # c3c's order is dependency order: keep it
    structs = {n for n, d in decls.items() if d["kind"] == "struct"}
    opaque = {n for n, d in decls.items() if d["opaque"]}

    protos = []
    for f in funcs:
        m = re.match(r"(.+?)\b(\w+)\((.*)\)$", f)
        if not m:
            raise Fail("cannot read prototype: %s" % f)
        name = m.group(2)
        if not name.startswith("bleu_"):
            raise Fail("exported function without the bleu_ prefix: %s" % name)
        ret = const_return(namer.text(m.group(1).strip()), structs, opaque)
        params = const_params(namer.text(m.group(3)), structs, opaque)
        protos.append({"name": name, "ret": ret, "params": params or "void",
                       "deps": set(IDENT.findall(ret + " " + params)), "service": service_of(name),
                       "doc": own.get(name, "")})

    needed = set()
    stack = [d for p in protos for d in p["deps"]]
    while stack:
        n = stack.pop()
        if n in needed or n not in decls:
            continue
        needed.add(n)
        stack.extend(decls[n]["deps"])
    for p in protos:
        for d in p["deps"]:
            if d.startswith("bleu_") and d not in decls and d != "bleu_slice_t" and d not in ("bleu_capi_slice",):
                raise Fail("%s uses undefined type %s" % (p["name"], d))

    return {"abi": abi.group(1), "decls": decls, "order": order, "needed": needed, "protos": protos}


def render(model):
    """{file name: text} for core.h, every service header and bleu.h."""
    decls, order, needed, protos = model["decls"], model["order"], model["needed"], model["protos"]
    out = {}
    for group in ["core"] + SERVICES:
        blocks = []
        for name in order:
            d = decls[name]
            if name not in needed or d["service"] != group:
                continue
            if d["kind"] == "enum":
                blocks.append(enum_block(name, d))
                continue
            text = d["body"]
            if d["kind"] == "struct":
                # Opaque structs are declared only; the others are declared, then defined.
                text = "typedef struct %s %s;%s" % (name, name, "" if text is None else "\n" + text)
            blocks.append(with_doc(d["doc"], text))
        for p in protos:
            if p["service"] != group:
                continue
            blocks.append(with_doc(p["doc"], "%s %s(%s);" % (p["ret"], p["name"], p["params"])))
        out[group] = blocks
    texts = {}
    for group, blocks in out.items():
        name = "core.h" if group == "core" else group + ".h"
        guard = "BLEU_CORE_H" if group == "core" else "BLEU_%s_H" % group.upper()
        head = [PREAMBLE.format(abi=model["abi"]), "#ifndef %s\n#define %s\n" % (guard, guard),
                "#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n"]
        if group == "core":
            head.append("#define BLEU_ABI_VERSION %s\n" % model["abi"])
            head.append(SLICE_DEFINITION)
        else:
            head.append('#include "core.h"\n')
        body = ["#ifdef __cplusplus\nextern \"C\" {\n#endif\n"] + ["\n\n".join(blocks) + "\n"] + \
               ["#ifdef __cplusplus\n}\n#endif\n\n#endif /* %s */\n" % guard]
        texts[name] = "\n".join(head + body)
    umbrella = ["/* Umbrella header: the whole Bleu C ABI. Generated by tools/capi/genheader.py. */",
                "#ifndef BLEU_BLEU_H", "#define BLEU_BLEU_H", '#include "core.h"']
    umbrella += ['#include "%s.h"' % s for s in SERVICES]
    umbrella += ["#endif /* BLEU_BLEU_H */", ""]
    texts["bleu.h"] = "\n".join(umbrella)
    return texts


def enum_block(name, d):
    prefix = upper_of(name) + "_"
    lines = ["typedef %s %s;" % (d["base"], name)]
    lines += ["#define %s%s %d" % (prefix, member, value) for member, value in d["members"]]
    return "\n".join(lines)


def with_doc(doc, text):
    if not doc:
        return text
    lines = [x.rstrip().replace("*/", "* /") for x in doc.split("\n")]
    if len(lines) == 1:
        return "/* %s */\n%s" % (lines[0], text)
    body = "\n".join(" * " + x if x else " *" for x in lines)
    return "/*\n%s\n */\n%s" % (body, text)


def check(texts):
    for name, text in texts.items():
        text = text.replace("__cplusplus", "")  # the C++ guard is the one legitimate `__`
        for bad in ["c3fault_t", "c3any_t", "c3typeid_t", "c3slice_t", "$", "std_", "__",
                    "String", "uint8_t*", "uint8_t ["]:
            if bad in text:
                raise Fail("%s: %r must not appear in a public header" % (name, bad))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--header", required=True, help="c3c-generated libbleu_capi.h")
    ap.add_argument("--src", required=True, help="libs/bleu_capi.c3l/src")
    ap.add_argument("--libs", required=True, help="the libs directory (docs of other libraries' types)")
    ap.add_argument("--out", required=True, help="output directory, normally include/bleu")
    ap.add_argument("--exports", help="also write the exported function names here, one per line")
    ap.add_argument("--check", action="store_true", help="fail if the output is stale; write nothing")
    args = ap.parse_args(argv)
    try:
        model = generate(args.header, args.src, args.libs)
        texts = render(model)
        check(texts)
    except Fail as e:
        print("genheader: error: %s" % e, file=sys.stderr)
        return 1
    if args.exports:
        with open(args.exports, "w", encoding="utf-8") as f:
            f.write("\n".join(p["name"] for p in model["protos"]) + "\n")
    stale = []
    for name, text in sorted(texts.items()):
        path = os.path.join(args.out, name)
        if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
            stale.append(name)
    if args.check:
        if stale:
            print("genheader: stale: %s (run tools/capi/build.sh)" % ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    os.makedirs(args.out, exist_ok=True)
    for name, text in sorted(texts.items()):
        with open(os.path.join(args.out, name), "w", encoding="utf-8") as f:
            f.write(text)
    print("genheader: wrote %d headers to %s" % (len(texts), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
