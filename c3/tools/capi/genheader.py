#!/usr/bin/env python3
"""Turn the header c3c writes for libbleu_capi into the public C headers.

    genheader.py --header <c3c-output>/libbleu_capi.h --src libs/bleu_capi.c3l/src \
                 --libs libs --out include/bleu [--check]

c3c's header is a faithful but raw description of the exported surface. This
tool makes it a public C API:

* Names: the C3 export names are kept (`bleu_battery_open`). Types that came
  from other Bleu modules, which C3 mangles as `bleu_battery__State` or
  `bleu_capi_battery_api__BatteryListener`, become `bleu_battery_state_t`. Enum
  members become `#define BLEU_BATTERY_KIND_UNKNOWN 0` (C3 emits them as global
  variables, which would be defined in every translation unit that includes the
  header). `c3slice_t`/`String` become `bleu_slice_t`; `uint8_t` pointers and
  arrays become `char` (C3's `char`); `char*` becomes `const char*` in fields and
  returns.
* Refusals: any `c3fault_t`, `c3any_t`, `c3typeid_t`, `$`, or leftover `std_`
  name in the output is an error. Faults and optionals must never be exposed.
* Reachability: only types an exported function (transitively) uses are emitted.
* Documentation: `<* ... *>` blocks in the C3 sources that precede an `@export`
  declaration are carried over as C comments.
* Opaque handles: a struct marked `// capi:opaque` is declared, not defined.
* Split: `bleu/core.h` holds shared types; `bleu/<service>.h` one per service in
  SERVICES; `bleu/bleu.h` includes them all.

Output is deterministic. `--check` writes nothing and fails if the files differ.
"""

import argparse
import os
import re
import sys

# Services with a C API. Adding one means adding its name here and an `*_api.c3`.
SERVICES = ["battery", "brightness"]

FORBIDDEN = re.compile(r"c3fault_t|c3any_t|c3typeid_t|\$|\bstd_|__\$|String\b")
MANGLED = re.compile(r"\bbleu(?:_capi(?:_\w+)?)?__([A-Za-z_]\w*)")
IDENT = re.compile(r"\b[A-Za-z_]\w*\b")

PREAMBLE = """\
/* Generated by tools/capi/genheader.py from libs/bleu_capi.c3l/src. Do not edit.
 * Regenerate with tools/capi/build.sh. C ABI version {abi}.
 */
"""

SLICE_DEFINITION = """\
/* A borrowed or owned run of elements: `len` items starting at `ptr`. The element
 * type is documented per field. Never free it; it belongs to the object it came from. */
typedef struct bleu_slice_t
{
	void* ptr;
	size_t len;
} bleu_slice_t;
"""


class Fail(Exception):
    pass


def snake(name):
    """CamelCase to snake_case: `BatteryListener` -> `battery_listener`."""
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", s)
    return s.lower()


def clean_type(c3name):
    """The C name of a mangled C3 type name, or the name unchanged if it is already clean."""
    m = re.fullmatch(r"bleu_capi(?:_\w+)?__(\w+)", c3name)
    if m:
        return "bleu_%s_t" % snake(m.group(1))
    m = re.fullmatch(r"bleu_(\w+?)__(\w+)", c3name)
    if m:
        return "bleu_%s_%s_t" % (m.group(1), snake(m.group(2)))
    m = re.fullmatch(r"std_collections_maybe__Maybe\$(.+)\$", c3name)
    if m:
        inner = m.group(1).split(".")[-1]
        return "bleu_maybe_%s_t" % snake(inner)
    return c3name


def upper_of(c_name):
    """`bleu_battery_kind_t` -> `BLEU_BATTERY_KIND`."""
    base = c_name[:-2] if c_name.endswith("_t") else c_name
    return base.upper()


def service_of(c_name):
    for svc in SERVICES:
        if c_name.startswith("bleu_%s_" % svc):
            return svc
    return None


# ---------------------------------------------------------------- c3c header

def split_statements(lines):
    """Top-level C statements of a section: each ends at a `;` outside braces."""
    out, buf, depth = [], [], 0
    for line in lines:
        if not buf and not line.strip():
            continue
        buf.append(line)
        depth += line.count("{") - line.count("}")
        if depth == 0 and line.rstrip().endswith(";"):
            out.append("\n".join(buf))
            buf = []
    if "".join(buf).strip():
        raise Fail("unterminated declaration: %r" % buf[0])
    return out


def parse_c3_header(text):
    """Return (types, functions): types is a list of dicts in c3c's order."""
    if "/* TYPES */" not in text or "/* FUNCTIONS */" not in text:
        raise Fail("not a c3c library header: missing /* TYPES */ or /* FUNCTIONS */")
    types_text = text.split("/* TYPES */", 1)[1].split("/* FUNCTIONS */", 1)[0]
    funcs_text = text.split("/* FUNCTIONS */", 1)[1]
    types = []
    for stmt in split_statements(types_text.split("\n")):
        types.append(classify(stmt.strip()))
    funcs = []
    for line in funcs_text.split("\n"):
        line = line.strip()
        if not line:
            continue
        if not line.startswith("extern ") or not line.endswith(";"):
            raise Fail("unexpected function line: %r" % line)
        funcs.append(line[len("extern "):-1])
    return types, funcs


def classify(stmt):
    """Sort one c3c statement into an item: enum, struct, typedef, fnptr or constant."""
    m = re.match(r"typedef enum (\w+)\s*\{(.*)\}\s*(\w+);", stmt, re.S)
    if m:
        members = [x.strip().rstrip(",") for x in m.group(2).split("\n") if x.strip()]
        return {"kind": "enum", "c3": m.group(3), "base": "int32_t", "values": members, "stmt": stmt}
    m = re.match(r"typedef struct (\w+)\s*;", stmt)
    if m:
        return {"kind": "forward", "c3": m.group(1), "stmt": stmt}
    m = re.match(r"struct (\w+)\s*\{(.*)\};", stmt, re.S)
    if m:
        body = [x.strip() for x in m.group(2).split(";") if x.strip()]
        return {"kind": "struct", "c3": m.group(1), "fields": body, "stmt": stmt}
    m = re.match(r"typedef (\w+) (\w+);$", stmt)
    if m and m.group(1) == "uint8_t" and False:
        pass
    m = re.match(r"typedef (\S+)\s+(\w+);", stmt)
    if m and "(" not in stmt:
        return {"kind": "typedef", "c3": m.group(2), "target": m.group(1), "stmt": stmt}
    m = re.match(r"typedef (\w+)\(\*(\w+)\)\((.*)\);", stmt)
    if m:
        return {"kind": "fnptr", "c3": m.group(2), "ret": m.group(1), "params": m.group(3), "stmt": stmt}
    m = re.match(r"(\w+) (\w+) = (-?\d+);", stmt)
    if m:
        return {"kind": "constant", "c3": m.group(2), "type": m.group(1), "value": m.group(3), "stmt": stmt}
    raise Fail("unrecognised declaration: %r" % stmt)


def group_enums(types):
    """Attach the global-variable constants (`T T_X = n;`) to their enum typedefs."""
    out = []
    by_type = {}
    for item in types:
        if item["kind"] == "constant":
            by_type.setdefault(item["type"], []).append(item)
            continue
        out.append(item)
        if item["kind"] == "typedef" and item["target"] == "uint8_t":
            item["kind"] = "enum"
            item["base"] = "uint8_t"
            item["values"] = []
            item["c3_values"] = by_type.get(item["c3"], [])
    for item in out:
        if item["kind"] == "enum" and item.get("c3_values"):
            for c in item["c3_values"]:
                item["values"].append((c["c3"][len(item["c3"]) + 1:], int(c["value"])))
    return out


# ------------------------------------------------------------- C3 sources

DOC_OPEN, DOC_CLOSE = "<*", "*>"


def scan_sources(src_dirs):
    """Doc comments and opaque markers from C3 sources, keyed by C name or declaration name.

    Returns (docs, opaque, own_decls): `docs` maps a declaration name (the export
    name, or the C3 name for aliases and other-module types) to its doc text;
    `opaque` is the set of export names marked `// capi:opaque`.
    """
    docs, opaque = {}, set()
    for path, lib in src_dirs:
        lines = open(path, encoding="utf-8").read().split("\n")
        doc, in_doc, pending_opaque = [], False, False
        for i, raw in enumerate(lines):
            line = raw.strip()
            if line.startswith(DOC_OPEN) and not in_doc:
                in_doc = True
                doc = []
                rest = line[len(DOC_OPEN):].strip()
                if rest:
                    doc.append(rest)
                if rest.endswith(DOC_CLOSE):
                    in_doc = False
                    doc = [x[:-len(DOC_CLOSE)].strip() for x in doc]
                continue
            if in_doc:
                if line.endswith(DOC_CLOSE):
                    in_doc = False
                    tail = line[:-len(DOC_CLOSE)].strip()
                    if tail:
                        doc.append(tail)
                    continue
                doc.append(line)
                continue
            if line == "// capi:opaque":
                pending_opaque = True
                continue
            decl = " ".join(lines[j].strip() for j in range(i, min(i + 6, len(lines))))
            m = re.search(r'@export\("([^"]+)"\)', decl)
            name = None
            if m and re.match(r"(fn|struct|enum|typedef)\b", line):
                name = m.group(1)
            else:
                a = re.match(r"alias (\w+) =", line)
                if a:
                    name = a.group(1)
                    if re.match(r"alias (\w+) = fn", line) and lib == "bleu_capi":
                        name = "bleu_capi:" + name
            if name is not None:
                if doc:
                    docs.setdefault(name, "\n".join(x for x in doc if x))
                if pending_opaque and m:
                    opaque.add(name)
            if line and not line.startswith("//") and name is not None or (line and not line.startswith("//")):
                pending_opaque = False
            if line == "" or line.startswith("//"):
                continue
            doc = []
    return docs, opaque


def library_docs(libs_dir):
    """Doc comments for other libraries' types, keyed by `<lib>/<Name>` for the C3 declaration."""
    found = {}
    for lib in sorted(os.listdir(libs_dir)):
        src = os.path.join(libs_dir, lib, "src")
        if not lib.endswith(".c3l") or not os.path.isdir(src):
            continue
        for fn in sorted(os.listdir(src)):
            if not fn.endswith(".c3") or fn.endswith("_test.c3"):
                continue
            lines = open(os.path.join(src, fn), encoding="utf-8").read().split("\n")
            doc = []
            for i, line in enumerate(lines):
                s = line.strip()
                if s.startswith("<*"):
                    doc = [s[2:].strip()] if s[2:].strip() else []
                    if s.endswith("*>"):
                        doc = [doc[0][:-2].strip()] if doc else []
                    continue
                if doc and not s.endswith("*>") and not s.startswith("*>"):
                    doc.append(s)
                    continue
                if doc:
                    tail = s[:-2].strip() if s.endswith("*>") else s
                    if tail:
                        doc.append(tail)
                    m = re.match(r"(?:typedef|struct|enum|alias|constset|bitstruct)\s+(\w+)", s)
                    if m and s.endswith(("*>",)) is False:
                        found.setdefault((lib[:-4], m.group(1)), "\n".join(x for x in doc if x))
                    doc = []
                    continue
                m = re.match(r"(?:typedef|struct|enum|alias|constset|bitstruct)\s+(\w+)", s)
                if m:
                    found.setdefault((lib[:-4], m.group(1)), "")
    return found


# ---------------------------------------------------------------- rewrite

class Rewriter:
    def __init__(self, items, typedef_subst):
        self.subst = typedef_subst  # std/c3 typedef name -> C type text
        self.clean = {}             # c3 name -> clean name for defined types
        for it in items:
            if it["kind"] in ("struct", "enum", "typedef", "fnptr", "forward"):
                self.clean[it["c3"]] = clean_type(it["c3"])

    def rewrite(self, text):
        text = text.replace("c3slice_t", "bleu_slice_t")

        def sub_ident(m):
            name = m.group(0)
            if name in self.subst:
                return self.rewrite(self.subst[name])
            if name in self.clean:
                return self.clean[name]
            if name == "bleu_slice_t":
                return name
            if MANGLED.match(name) or name.startswith("bleu_"):
                return clean_type(name)
            return name

        text = IDENT.sub(sub_ident, text)
        text = re.sub(r"\buint8_t(\s*\*|\s+\w+\s*\[)", r"char\1", text)
        return text


def build_typedef_subst(items):
    subst = {"String": "c3slice_t"}
    for it in items:
        if it["kind"] == "typedef" and not it["c3"].startswith("bleu_"):
            subst[it["c3"]] = it["target"]
    return subst


# ---------------------------------------------------------------- generate

def generate(c3_header, src_dir, libs_dir):
    text = open(c3_header, encoding="utf-8").read()
    items, funcs = parse_c3_header(text)
    items = group_enums(items)
    src_files = []
    for fn in sorted(os.listdir(src_dir)):
        if fn.endswith(".c3") and not fn.endswith("_test.c3"):
            src_files.append((os.path.join(src_dir, fn), "bleu_capi"))
    docs, opaque = scan_sources(src_files)
    abi = re.search(r"const uint ABI_VERSION = (\d+);", open(os.path.join(src_dir, "core.c3")).read())
    if not abi:
        raise Fail("core.c3 has no `const uint ABI_VERSION = N;`")
    lib_docs = library_docs(libs_dir)

    rw = Rewriter(items, build_typedef_subst(items))
    decls = {}   # clean name -> {kind, text, deps, service, doc}
    order = []

    def doc_for(c3name, clean):
        if c3name in docs:
            return docs[c3name]
        if "bleu_capi" in c3name:
            return docs.get(c3name.split("__")[-1], "")
        m = MANGLED.match(c3name)
        if m:
            mod = c3name[len("bleu_"):].split("__")[0]
            for lib in ("bleu_" + mod, "bleu_core"):
                if (lib, m.group(1)) in lib_docs:
                    return lib_docs[(lib, m.group(1))]
        return ""

    for it in items:
        k = it["kind"]
        if k == "typedef" and not it["c3"].startswith(("bleu_", "std_")) and it["c3"] in rw.subst:
            continue
        if k == "typedef" and it["c3"].startswith("std_"):
            continue
        if k == "typedef" and it["c3"] == "String":
            continue
        if k == "forward":
            continue
        clean = rw.clean.get(it["c3"], it["c3"])
        if k == "typedef":
            target = rw.rewrite(it["target"])
            if FORBIDDEN.search(target):
                raise Fail("typedef %s leaks %s" % (clean, target))
            text_out = "typedef %s %s;" % (target, clean)
            deps = set(IDENT.findall(target))
        elif k == "enum":
            base = it["base"]
            text_out = "typedef %s %s;" % (base, clean)
            deps = set()
        elif k == "fnptr":
            ret = rw.rewrite(it["ret"])
            params = rw.rewrite(it["params"])
            text_out = "typedef %s(*%s)(%s);" % (ret, clean, params)
            deps = set(IDENT.findall(ret + " " + params))
        elif k == "struct":
            if it["c3"] in opaque or clean in opaque:
                text_out = None
                deps = set()
            else:
                fields = []
                deps = set()
                for f in it["fields"]:
                    fr = rw.rewrite(f)
                    if FORBIDDEN.search(fr):
                        raise Fail("struct %s leaks %s" % (clean, fr))
                    fr = re.sub(r"\bchar\*(\s*\w)", r"const char*\1", fr)
                    fields.append(fr)
                    deps |= set(IDENT.findall(fr))
                text_out = "struct %s\n{\n%s\n};" % (clean, "\n".join("\t%s;" % f for f in fields))
        else:
            raise Fail("unhandled item %s" % k)
        decl = {"kind": k, "text": text_out, "deps": deps, "clean": clean,
                "doc": doc_for(it["c3"], clean), "opaque": clean in opaque or it["c3"] in opaque}
        if clean in decls:
            raise Fail("two C3 types map to %s" % clean)
        decls[clean] = decl
        order.append(clean)

    for clean in order:
        if decls[clean]["kind"] == "enum":
            pass

    # Enum members become #define constants; they are emitted with their enum.
    enum_defines = {}
    for it in items:
        if it["kind"] != "enum":
            continue
        clean = rw.clean.get(it["c3"], it["c3"])
        prefix = upper_of(clean) + "_"
        lines = []
        for idx, val in enumerate(it["values"]):
            if isinstance(val, tuple):
                member, number = val
            else:
                member = val.split("=")[0].strip()
                member = member[len(it["c3"]) + 1:] if member.startswith(it["c3"] + "_") else member.split("_", 1)[-1]
                number = idx
            lines.append("#define %s%s %d" % (prefix, member, number))
        enum_defines[clean] = lines

    # Reachability from the functions.
    func_info = []
    for f in funcs:
        m = re.match(r"(.+?)\b(\w+)\((.*)\)$", f)
        if not m:
            raise Fail("cannot read prototype: %s" % f)
        ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
        rret = rw.rewrite(ret)
        rparams = rw.rewrite(params)
        if FORBIDDEN.search(rret + rparams):
            raise Fail("function %s leaks a C3 type: %s" % (name, f))
        if not name.startswith("bleu_"):
            raise Fail("exported function without the bleu_ prefix: %s" % name)
        rret = fix_const_return(rret, decls, opaque)
        rparams = fix_const_params(rparams, decls)
        func_info.append({"name": name, "ret": rret, "params": rparams, "deps": set(IDENT.findall(rret + " " + rparams))})

    needed, stack = set(), []
    for fi in func_info:
        stack.extend(fi["deps"])
    while stack:
        n = stack.pop()
        if n in needed or n not in decls:
            continue
        needed.add(n)
        stack.extend(decls[n]["deps"])

    for fi in func_info:
        for dep in fi["deps"]:
            if dep not in decls and dep not in ("void", "char", "bool", "int32_t", "uint32_t", "int64_t", "uint64_t",
                                                  "uint8_t", "size_t", "ptrdiff_t", "float", "double", "int", "const",
                                                  "unsigned", "long", "short") and not dep.startswith(("bleu_slice", "BLEU")):
                if dep.startswith("bleu_") and dep not in enum_defines:
                    raise Fail("function %s uses undefined type %s" % (fi["name"], dep))
    return {"abi": abi.group(1), "decls": decls, "order": order, "needed": needed,
            "funcs": func_info, "enum_defines": enum_defines, "docs": docs}


def fix_const_return(ret, decls, opaque):
    """Struct pointers returned from accessors are borrowed: make them const."""
    m = re.fullmatch(r"(\w+)\s*\*", ret.strip())
    if m and m.group(1) in decls and decls[m.group(1)]["kind"] == "struct" and not decls[m.group(1)]["opaque"]:
        return "const %s*" % m.group(1)
    if ret.strip() == "char*":
        return "const char*"
    return ret


def fix_const_params(params, decls):
    """Read-only struct pointers are const. Out-parameters (named out*) and opaque handles are not."""
    out = []
    for p in params.split(","):
        p = p.strip()
        if not p or p == "void":
            out.append(p)
            continue
        m = re.fullmatch(r"(\w+)\s*\*\s*(\w+)", p)
        if m and m.group(1) in decls and decls[m.group(1)]["kind"] == "struct" \
                and not decls[m.group(1)]["opaque"] and not m.group(2).startswith("out"):
            p = "const %s* %s" % (m.group(1), m.group(2))
        out.append(p)
    return ", ".join(out)


def render(model, svc_of_fn):
    """Return {file name: text} for core.h, each service, and bleu.h."""
    decls, order, needed = model["decls"], model["order"], model["needed"]
    funcs = model["funcs"]

    def in_group(name, group):
        return svc_of(name) == group

    def svc_of(name):
        return service_of(name) or ("core")

    files = {}
    groups = ["core"] + SERVICES
    for group in groups:
        body = []
        for clean in order:
            if clean not in needed or svc_of(clean) != group:
                continue
            d = decls[clean]
            if group == "core" and clean.startswith("bleu_slice"):
                continue
            block = []
            if d["doc"]:
                block.append(format_doc(d["doc"]))
            if d["kind"] == "enum":
                block.append("typedef %s %s;" % (d["text"].split()[1], clean) if False else d["text"])
                block.extend(model["enum_defines"].get(clean, []))
            elif d["kind"] == "struct":
                if d["text"] is None:
                    block.append("typedef struct %s %s;" % (clean, clean))
                else:
                    block.append("typedef struct %s %s;" % (clean, clean))
                    block.append(d["text"])
            else:
                block.append(d["text"])
            body.append("\n".join(block))
        for fi in funcs:
            if svc_of(fi["name"]) != group:
                continue
            doc = model["docs"].get(fi["name"], "")
            block = [format_doc(doc)] if doc else []
            block.append("%s %s(%s);" % (fi["ret"], fi["name"], fi["params"] or "void"))
            body.append("\n".join(block))
        files[group] = body
    return files


def format_doc(text):
    lines = [x.rstrip() for x in text.split("\n")]
    lines = [x.replace("*/", "* /") for x in lines]
    if len(lines) == 1:
        return "/* %s */" % lines[0]
    return "/*\n" + "\n".join(" * " + x if x else " *" for x in lines) + "\n */"


def assemble(model, files):
    """The text of each header, with guards, C linkage and the shared preamble."""
    out = {}
    abi = model["abi"]
    for group, body in files.items():
        guard = "BLEU_%s_H" % group.upper() if group != "core" else "BLEU_CORE_H"
        includes = ["#include <stdbool.h>", "#include <stddef.h>", "#include <stdint.h>"]
        parts = [PREAMBLE.format(abi=abi), "#ifndef %s\n#define %s\n" % (guard, guard)]
        parts.append("\n".join(includes) + "\n")
        if group == "core":
            parts.append("#define BLEU_ABI_VERSION %s\n" % abi)
            parts.append(SLICE_DEFINITION)
        else:
            parts.append('#include "core.h"\n')
        parts.append("#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
        parts.append("\n\n".join(body) + "\n")
        parts.append("#ifdef __cplusplus\n}\n#endif\n\n#endif /* %s */\n" % guard)
        out[group + ".h"] = "\n".join(parts)
    umbrella = ["/* Umbrella header: the whole Bleu C ABI. Generated; do not edit. */",
                "#ifndef BLEU_BLEU_H", "#define BLEU_BLEU_H", '#include "core.h"']
    umbrella += ['#include "%s.h"' % s for s in SERVICES]
    umbrella += ["#endif /* BLEU_BLEU_H */", ""]
    out["bleu.h"] = "\n".join(umbrella)
    return out


def check_text(name, text):
    for bad in ["c3fault_t", "c3any_t", "c3typeid_t", "c3slice_t", "$", "std_", "__", "String", "uint8_t*", "uint8_t ["]:
        if bad in text:
            raise Fail("%s: forbidden %r in the public header" % (name, bad))
    for m in re.finditer(r"\bbleu_\w+", text):
        pass


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--header", required=True, help="c3c-generated libbleu_capi.h")
    ap.add_argument("--src", required=True, help="libs/bleu_capi.c3l/src")
    ap.add_argument("--libs", required=True, help="libs directory (for docs of other libraries' types)")
    ap.add_argument("--out", required=True, help="output include/bleu directory")
    ap.add_argument("--check", action="store_true", help="fail if the output directory is stale; write nothing")
    args = ap.parse_args(argv)
    try:
        model = generate(args.header, args.src, args.libs)
        files = assemble(model, render(model, None))
        for name, text in files.items():
            check_text(name, text)
    except Fail as e:
        print("genheader: error: %s" % e, file=sys.stderr)
        return 1
    stale = []
    for name, text in sorted(files.items()):
        path = os.path.join(args.out, name)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            stale.append(name)
    if args.check:
        if stale:
            print("genheader: stale: %s (run tools/capi/build.sh)" % ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    os.makedirs(args.out, exist_ok=True)
    for name, text in sorted(files.items()):
        with open(os.path.join(args.out, name), "w", encoding="utf-8") as f:
            f.write(text)
    print("genheader: wrote %s" % ", ".join(sorted(files)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
